// Example 0: the hook. Six lines of arithmetic that don't do what you expect.
// Run it with:  java Ex00MathSurprises.java
// Before you run it, write down what you think each line will print.

public class Ex00MathSurprises {
    public static void main(String[] args) {
        System.out.println(7 / 2);
        System.out.println(0.1 + 0.2);
        System.out.println(2147483647 + 1);
        System.out.println('A' + 1);
        System.out.println(1 + 2 + "3");
        System.out.println("1" + 2 + 3);
    }
}
